#!/usr/bin/env node
// Turns a mongoexport of every collection (one <collection>.json array per file, relaxed Extended JSON) into SQL for
// D1: every table emptied and refilled, documents unchanged except for MongoDB types:
//   {"$oid": ...}   _id is dropped (the Worker never used it)
//   {"$date": ...}  becomes the ISO string the Worker writes (util.ts isoAt): "2026-09-16T20:35:44.062000+00:00"
//   $numberLong / $numberInt / $numberDouble / $numberDecimal become numbers
// Anything else unexpected stops the import.
//
// Usage: node scripts/import-mongo.mjs <export dir> <out.sql>
//        npx wrangler d1 execute broscafe --remote --file <out.sql>
// Re-runnable: it replaces all data, so it can be repeated on switch night.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [dir, out] = process.argv.slice(2);
if (!dir || !out) {
  console.error('usage: import-mongo.mjs <export dir> <out.sql>');
  process.exit(1);
}

const COLLECTIONS = [
  'users', 'members', 'transactions', 'analytics_events', 'magic_tokens', 'settings', 'content', 'products', 'media',
  'contact_log', 'game_runs', 'wallet_registrations', 'voided_passes', 'wallet_stats', 'sales_days', 'live_sales',
  'sales_forecasts', 'special_days', 'social_posts',
];

/** Same as util.ts isoAt: millisecond precision padded to Python's microseconds, "+00:00". */
const isoAt = (d) => d.toISOString().replace(/\.(\d{3})Z$/, '.$1000+00:00');

function convert(v, where) {
  if (Array.isArray(v)) return v.map((x, i) => convert(x, `${where}[${i}]`));
  if (v && typeof v === 'object') {
    const keys = Object.keys(v);
    if (keys.length === 1 && keys[0].startsWith('$')) {
      const [k] = keys;
      const x = v[k];
      if (k === '$date') {
        const ms = typeof x === 'object' && x.$numberLong !== undefined ? Number(x.$numberLong) : x;
        const d = new Date(ms);
        if (Number.isNaN(d.getTime())) throw new Error(`bad date at ${where}: ${JSON.stringify(x)}`);
        return isoAt(d);
      }
      if (k === '$numberLong' || k === '$numberInt' || k === '$numberDouble' || k === '$numberDecimal') return Number(x);
      throw new Error(`unsupported type ${k} at ${where}`);
    }
    const o = {};
    for (const [k, x] of Object.entries(v)) if (k !== '_id') o[k] = convert(x, `${where}.${k}`);
    return o;
  }
  return v;
}

const files = new Set(readdirSync(dir));
const sql = ['-- generated by scripts/import-mongo.mjs; replaces all data'];
const counts = {};
for (const c of COLLECTIONS) {
  sql.push(`DELETE FROM ${c};`);
  if (!files.has(`${c}.json`)) {
    counts[c] = 0;
    continue;
  }
  const docs = JSON.parse(readFileSync(join(dir, `${c}.json`), 'utf8'));
  counts[c] = docs.length;
  docs.forEach((d, i) => {
    const doc = JSON.stringify(convert(d, `${c}[${i}]`));
    sql.push(`INSERT INTO ${c} (doc) VALUES ('${doc.replace(/'/g, "''")}');`);
  });
}
const unknown = [...files].filter((f) => f.endsWith('.json') && !COLLECTIONS.includes(f.slice(0, -5)));
if (unknown.length) throw new Error(`export has collections the Worker does not know: ${unknown.join(', ')}`);
writeFileSync(out, sql.join('\n') + '\n');
console.log(JSON.stringify(counts));
