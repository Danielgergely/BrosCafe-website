"""Pre-render the Wallet artwork with the Python code itself, for the Worker (which has no Pillow).

Renders every strip (Apple, 1x/2x/3x) and hero (Google) image that backend/app/wallet/artwork.py can produce for the
states the API serves: each tier x required 0..50 x stamps 0..required. Stamps above `required` draw the same image
as stamps == required, and required 0 ignores stamps, so the Worker maps those requests onto these keys
(see src/wallet/artwork.ts). Also regenerates src/wallet/pass_assets.ts from backend/assets (icons and logos).

    backend/.venv/bin/python worker/scripts/render_wallet_art.py OUT_DIR
    cd worker && npx wrangler r2 bulk put broscafe-media --remote -J eu -f OUT_DIR/bulk.json \
        --ct image/png --cc "public, max-age=31536000, immutable"

Run it again (and re-upload) whenever artwork.py or Pillow changes.
"""
import base64
import json
import sys
from multiprocessing import Pool
from pathlib import Path

WORKER = Path(__file__).resolve().parent.parent
BACKEND = WORKER.parent / "backend"
sys.path.insert(0, str(BACKEND))

from app.wallet import artwork  # noqa: E402

MAX = 50  # the hero route's bound: 0 <= stamps, required <= 50
SCALES = ((1, ""), (2, "@2x"), (3, "@3x"))
PREFIX = "wallet-art"


def jobs():
    for tier in artwork.TIERS:
        for required in range(MAX + 1):
            for stamps in range(required + 1):
                for scale, suffix in SCALES:
                    yield ("strip", tier, stamps, required, scale, f"strip/{tier}/{stamps}-{required}{suffix}.png")
                yield ("hero", tier, stamps, required, 0, f"hero/{tier}/{stamps}-{required}.png")


def render(job):
    out, kind, tier, stamps, required, scale, rel = job
    data = artwork.strip(tier, stamps, required, scale) if kind == "strip" else artwork.hero(tier, stamps, required)
    path = Path(out) / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return rel, len(data)


def write_pass_assets():
    names = [p.name for p in sorted((BACKEND / "assets").glob("*.png"))]
    lines = ["// Generated by scripts/render_wallet_art.py from backend/assets. Do not edit.",
             "export const PASS_ASSETS: Record<string, string> = {"]
    for name in names:
        b64 = base64.b64encode((BACKEND / "assets" / name).read_bytes()).decode()
        lines.append(f"  '{name}': '{b64}',")
    lines.append("};")
    (WORKER / "src" / "wallet" / "pass_assets.ts").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    OUT = Path(sys.argv[1]).resolve()
    OUT.mkdir(parents=True, exist_ok=True)
    with Pool() as pool:
        done = pool.map(render, [(str(OUT), *job) for job in jobs()], chunksize=64)
    (OUT / "bulk.json").write_text(json.dumps([{"key": f"{PREFIX}/{rel}", "file": str(OUT / rel)} for rel, _ in done]))
    write_pass_assets()
    total = sum(n for _, n in done)
    print(f"{len(done)} images, {total / 1e6:.1f} MB in {OUT}")
