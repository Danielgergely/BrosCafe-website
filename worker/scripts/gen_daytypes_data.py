"""Writes src/services/daytypes_data.ts: Hungarian days off and working Saturdays per year, exactly as
backend/app/services/daytypes.py's _calendar() computes them with the `holidays` package (no JS equivalent).

Run from the repo root with the backend's virtualenv, after updating `holidays` or to extend the years:
    backend/.venv/bin/python worker/scripts/gen_daytypes_data.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

import holidays  # noqa: E402

from app.services.daytypes import _calendar  # noqa: E402

# day_info() looks one year either side for working Saturdays and payday() can step into the previous month,
# so a margin of one year each side keeps 2024-2032 complete.
FIRST, LAST = 2022, 2034

calendar = {}
for year in range(FIRST, LAST + 1):
    days_off, workdays = _calendar(year)
    calendar[str(year)] = {"days_off": days_off, "workdays": workdays}

out = ROOT / "worker" / "src" / "services" / "daytypes_data.ts"
out.write_text(
    "// Generated by worker/scripts/gen_daytypes_data.py from the Python `holidays` package "
    f"{holidays.__version__}. Do not edit.\n"
    "// {year: {days_off: {date: {name, name_hu}}, workdays: {date: name}}}, as daytypes.py's _calendar(year).\n"
    f"export const FIRST_YEAR = {FIRST};\nexport const LAST_YEAR = {LAST};\n"
    "export const CALENDAR: Record<string, { days_off: Record<string, { name: string; name_hu: string }>; "
    "workdays: Record<string, string> }> = "
    + json.dumps(calendar, ensure_ascii=False, indent=1) + ";\n",
    encoding="utf-8",
)
print(f"wrote {out}")
